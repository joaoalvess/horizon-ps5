"""Qualify pipeline waits and shader reuse with cold/warm Mario Kart World boots.

Run with an input-enabled native candidate and matching packaged ELF. Uses the
existing console lease, PT_LOAD verification and reversible backup helpers.
Keeps private saves/configuration local. Never uploads game content.
"""
import argparse
import importlib.util
import json
import os
from pathlib import Path
import re
import socket
import subprocess
import sys
import threading
import time

helper = Path(__file__).with_name('check-nir-console.py')
spec = importlib.util.spec_from_file_location('console_helpers', helper)
helpers = importlib.util.module_from_spec(spec)
spec.loader.exec_module(helpers)
TITLE = '0400c3f00006e000'


class CacheConsole(helpers.Console):
    def __init__(self, args):
        super().__init__(args)
        self.token = 'pipeline-cache-' + str(time.time_ns())

    def initialize(self):
        self.stop()
        for path in [self.app + '/' + name for name in ('env.txt', 'dev-settings.txt', 'compat-input.txt')]:
            self.backups[path] = self.get(path, True)
        config_path = self.data + '/config/eglantineps5.json'
        self.backups[config_path] = self.get(config_path)
        private = self.out / 'private-backup'
        private.mkdir()
        for index, (_, data) in enumerate(self.backups.items()):
            if data is not None:
                (private / str(index)).write_bytes(data)
        self.original_hash = helpers.digest(self.get(self.app + '/eboot.bin'))
        temporary = self.app + '/.' + self.token + '.bin'
        self.generated.append(temporary)
        self.put(temporary, self.args.candidate.read_bytes())
        view = self.get(temporary)
        if helpers.load_segments(view) != helpers.load_segments(self.args.elf.read_bytes()):
            raise RuntimeError('Uploaded PT_LOAD segments differ from candidate ELF')
        self.candidate_hash = helpers.digest(view)
        if helpers.digest(self.get(self.app + '/eboot.bin')) != self.original_hash:
            raise RuntimeError('Executable changed before deployment')
        self.original_eboot = self.app + '/eboot.bin.' + self.token
        self.rename(self.app + '/eboot.bin', self.original_eboot)
        self.deployed = True
        self.rename(temporary, self.app + '/eboot.bin')
        config = json.loads(self.backups[config_path])
        if self.args.resolution:
            config.setdefault('games', {}).setdefault(TITLE.upper(), {})['resolution'] = self.args.resolution
            self.put(config_path, json.dumps(config, indent=2).encode())
        profile = config['profiles']['current']
        save = self.data + '/user/nand/user/save/0000000000000000/' + profile + '/' + TITLE.upper()
        if self.exists(save):
            self.download_tree(save, private / 'save')
            self.save_backup = save + '.' + self.token
            self.rename(save, self.save_backup)
            self.save = save
            self.upload_tree(private / 'save', save)
        else:
            # Remove only save data generated by this test if the title has never saved.
            self.new_save = save
        for path in [self.data + '/user/cache/shader/' + TITLE,
                     self.data + '/user/cache/shader/vulkan_static_pipelines.bin', self.data + '/cache/radv']:
            backup = path + '.' + self.token if self.exists(path) else None
            if backup:
                self.rename(path, backup)
            self.caches.append((path, backup))
        self.put(self.app + '/env.txt',
                 b'MESA_SHADER_CACHE_SHOW_STATS=true\nEDEN_NX2_COMPILE_TIMES=1\nEDEN_LOG_FILTER=*:Warning Render.Vulkan:Info\n')
        self.put(self.app + '/dev-settings.txt', b'replay=off\n')
        self.remove(self.app + '/compat-input.txt')
        (self.out / 'receipt.json').write_text(json.dumps({
            'candidate_self_sha256': helpers.digest(self.args.candidate.read_bytes()),
            'candidate_ftp_elf_sha256': self.candidate_hash,
            'original_sha256': self.original_hash, 'load_segments_verified': True,
            'caches': self.caches, 'token': self.token}, indent=2))
        self.thread = threading.Thread(target=self.klog, daemon=True)
        self.thread.start()
        self.log('Candidate PT_LOAD verified; original executable/settings/caches backed up')

    def cache_files(self, path):
        if not self.exists(path):
            return []
        files = []
        for name, facts in self.entries(path):
            if facts['type'] == 'dir':
                files.extend(self.cache_files(path + '/' + name))
            else:
                files.append({'path': path + '/' + name, 'bytes': int(facts.get('size', 0))})
        return files

    def run_cache(self, label):
        self.stop()
        # A stop pulse belongs only to its previous process, including release twins.
        self.remove(self.app + '/compat-input.txt')
        self.current = self.out / label
        self.current.mkdir()
        before = self.get(self.data + '/logs/boot-trace.txt', True)
        before = before.splitlines()[0] if before else b''
        with socket.create_connection((self.args.host, 9021), timeout=10) as client:
            client.sendall(self.args.launcher.read_bytes())
            client.shutdown(socket.SHUT_WR)
        deadline = time.monotonic() + 90
        while True:
            data = self.get(self.data + '/logs/boot-trace.txt', True)
            if data and data.splitlines()[0] != before:
                boot = data.splitlines()[0]
                break
            if time.monotonic() > deadline:
                raise RuntimeError('No fresh process boot')
            time.sleep(1)
        self.log(label + ': ' + boot.decode(errors='replace'))
        start = time.monotonic()
        last_collect = -30
        while time.monotonic() - start < self.args.seconds:
            elapsed = time.monotonic() - start
            if elapsed - last_collect >= 30:
                self.collect()
                if (self.current / 'boot.txt').read_bytes().splitlines()[0] != boot:
                    raise RuntimeError('Unexpected application restart')
                text = (self.current / 'boot.txt').read_text(errors='replace')
                self.log(f'{label} {elapsed:.0f}s loaded={"game loaded (status 0)" in text}')
                last_collect = elapsed
            time.sleep(1)
        self.collect()
        self.screenshot('title')
        boot_text = (self.current / 'boot.txt').read_text(errors='replace')
        if boot_text.splitlines()[0].encode() != boot:
            raise RuntimeError('Application restarted before the final capture; inspect crash-index and klog')
        if 'game loaded (status 0)' not in boot_text:
            raise RuntimeError('Mario Kart World did not finish loading')
        # Return to the launcher normally so Vulkan caches serialize and Mesa prints hit stats.
        self.pulse(mask=0x100000 | 0x400, duration=500)
        time.sleep(12)
        self.collect()
        heap = (self.current / 'heap.log').read_text(errors='replace')
        stderr = (self.current / 'stderr.log').read_text(errors='replace')
        eden = (self.current / 'eden_log.txt').read_text(errors='replace')
        if 'mutex lock failed' in stderr + eden or 'Cannot allocate memory' in stderr + eden:
            raise RuntimeError('Resource-exhaustion failure in console logs')
        if 'phase=first_frame_callback' not in heap:
            raise RuntimeError('No first guest frame callback')
        summary = {
            'label': label, 'game_loaded': True,
            'cache_stats': re.findall(r'disk shader cache:.*', stderr),
            'total_cached_pipeline_counts': re.findall(r'Total Pipeline Count: (\d+)', eden),
            'frame_samples': re.findall(r'EDEN_VULKAN_FRAME[^\n]*', heap)[-5:],
            'cache_messages': [line for line in stderr.splitlines() if 'shader cache' in line or 'filesystem access' in line],
            'radv_files': self.cache_files(self.data + '/cache/radv'),
            'title_files': self.cache_files(self.data + '/user/cache/shader/' + TITLE),
        }
        (self.current / 'summary.json').write_text(json.dumps(summary, indent=2))
        self.log(f'{label}: {len(summary["radv_files"])} driver-cache files; {summary["cache_stats"]}')
        self.stop()
        return summary

    def restore(self):
        if getattr(self, 'new_save', None) and self.deployed:
            if helpers.digest(self.get(self.app + '/eboot.bin')) != self.candidate_hash:
                raise RuntimeError('Executable changed; retaining backups')
            self.stop()
            if self.exists(self.new_save):
                self.remove(self.new_save)
        super().restore()



def verify_results(results):
    by_label = {entry['label']: entry for entry in results}
    for label in ('cold', 'warm-disk', 'warm'):
        if not by_label[label]['game_loaded']:
            raise RuntimeError(label + ': game load was not verified')
    driver_hits = sum(int(hit) for line in by_label['warm-disk']['cache_stats']
                      for hit in re.findall(r'hits = (\d+)', line))
    if driver_hits == 0:
        raise RuntimeError('Warm driver disk cache had no verified hits')
    for label in ('warm-disk', 'warm'):
        if not any(int(count) > 0 for count in by_label[label]['total_cached_pipeline_counts']):
            raise RuntimeError(label + ': no cached emulator pipelines were loaded')
    if not by_label['cold']['radv_files']:
        raise RuntimeError('Cold run did not persist a driver cache')
    return {'warm_disk_hits': driver_hits, 'cache_reuse_verified': True}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--host', required=True, help='Console IP address')
    for key in ('candidate', 'elf', 'launcher', 'out'):
        parser.add_argument('--' + key, type=Path, required=True)
    parser.add_argument('--seconds', type=int, default=90)
    parser.add_argument('--resolution', choices=('0.5x', '0.75x', '1x'), help='Temporary per-game test resolution')
    args = parser.parse_args()
    for path in (args.candidate, args.elf, args.launcher):
        if not path.is_file():
            parser.error('Missing input: ' + str(path))
    if os.environ.get('EGLANTINE_CONSOLE_LEASE_HOST') != args.host:
        subprocess.run([sys.executable, str(Path(__file__).with_name('console-lease.py')),
                        '--host', args.host, '--owner', 'pipeline-cache-check', 'run', '--wait', '--',
                        sys.executable, str(Path(__file__).resolve()), *sys.argv[1:]], check=True)
        return
    console = CacheConsole(args)
    try:
        console.initialize()
        results = [console.run_cache('cold')]
        # Keep the driver disk cache, but remove only this test's Vulkan blob.
        # This isolates disk-cache hits from Vulkan pipeline-cache blob reuse.
        for entry in results[0]['title_files']:
            if entry['path'].rsplit('/', 1)[-1].startswith('vulkan_pipelines.'):
                console.remove(entry['path'])
        results.append(console.run_cache('warm-disk'))
        results.append(console.run_cache('warm'))
        (console.out / 'results.json').write_text(json.dumps(results, indent=2))
        (console.out / 'verification.json').write_text(json.dumps(verify_results(results), indent=2))
    finally:
        console.restore()


if __name__ == '__main__':
    main()
